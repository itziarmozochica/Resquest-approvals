import { ChangeDetectionStrategy, Component, computed, input, output, signal, WritableSignal } from '@angular/core';

import { TranslateModule } from '@ngx-translate/core';

import { NamedDateRangeV1, ProductRow, ScheduleDemandTier, SessionSlotV1 } from '../../models/event-schedule-composer-v1.model';

interface WeekdayView {
  dow: number;
  key: string;
  label: string;
  open: boolean;
}

/** Shared editor state for the two "generate slots" modals (per-day recurrence and across-days). */
interface SlotGenerator {
  open: WritableSignal<boolean>;
  from: WritableSignal<string>;
  to: WritableSignal<string>;
  each: WritableSignal<number | null>;
  tier: WritableSignal<ScheduleDemandTier>;
  productIds: WritableSignal<string[]>;
  error: WritableSignal<string>;
}

function createSlotGenerator(): SlotGenerator {
  return {
    each: signal<number | null>(null),
    error: signal<string>(''),
    from: signal<string>(''),
    open: signal<boolean>(false),
    productIds: signal<string[]>([]),
    tier: signal<ScheduleDemandTier>(''),
    to: signal<string>(''),
  };
}

const DOW_ORDER = [1, 2, 3, 4, 5, 6, 0];
const DOW_LABELS: Record<number, string> = { 0: 'Sun', 1: 'Mon', 2: 'Tue', 3: 'Wed', 4: 'Thu', 5: 'Fri', 6: 'Sat' };
const HM = /^\d{2}:\d{2}$/;

/**
 * Weekdays step of the band wizard: pick selling weekdays, one session duration for the whole band, and
 * per-weekday collapsible cards of time slots. Each slot carries a single demand tier and its own product
 * set. Slots can be added one at a time, generated by a per-day time recurrence, or generated across many
 * days at once. Emits a new band on every edit.
 */
@Component({
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [TranslateModule],
  selector: 'app-ir-schedule-wizard-step-weekdays',
  standalone: true,
  styleUrls: ['./ir-schedule-wizard-step-weekdays.component.scss'],
  templateUrl: './ir-schedule-wizard-step-weekdays.component.html',
})
export class IrScheduleWizardStepWeekdaysComponent {
  readonly band = input.required<NamedDateRangeV1>();
  readonly products = input<ProductRow[]>([]);
  readonly validationAttempted = input<boolean>(false);
  readonly bandChange = output<NamedDateRangeV1>();

  readonly collapsedDays = signal<Record<string, boolean>>({});

  // Multiple time slots generator modal (single/multiple weekdays depending on the mode)
  readonly generator = createSlotGenerator();
  readonly generatorMode = signal<'day' | 'days'>('day');
  readonly recurrenceDow = signal<string>(''); // target weekday in 'day' mode
  readonly generateDows = signal<Record<string, boolean>>({}); // selected weekdays in 'days' mode

  readonly weekdays = computed<WeekdayView[]>(() => {
    const only = this.band().onlyDows ?? [];
    return DOW_ORDER.map(dow => ({ dow, key: String(dow), label: DOW_LABELS[dow], open: only.includes(dow) }));
  });

  readonly openWeekdays = computed<WeekdayView[]>(() => this.weekdays().filter(w => w.open));

  readonly #productById = computed<Map<string, ProductRow>>(() => new Map(this.products().map(p => [p.id, p])));

  // ── Reads ──────────────────────────────────────────────────────────────────

  duration(): number | null {
    return this.band().durationMin ?? null;
  }

  slotsFor(dowKey: string): SessionSlotV1[] {
    return this.band().dowSlots?.[dowKey] ?? [];
  }

  isDayCollapsed(dowKey: string): boolean {
    return this.collapsedDays()[dowKey] ?? false;
  }

  productName(productId: string): string {
    return this.#productById().get(productId)?.name ?? productId;
  }

  slotHasProduct(slot: SessionSlotV1, productId: string): boolean {
    return slot.productIds.includes(productId);
  }

  /** Whether a product has a configured Peak/Valley subcategory, so we only offer those tiers. */
  hasTier(product: ProductRow, tier: 'Peak' | 'Valley'): boolean {
    const category = tier.toLowerCase();
    return (product.subcategories ?? []).some(
      s =>
        String(s.category ?? '')
          .trim()
          .toLowerCase() === category,
    );
  }

  /** Demand-tier options for a set of products: Standard always, Peak/Valley only when some product supports them. */
  tierOptionsFor(productIds: string[]): ScheduleDemandTier[] {
    const chosen = productIds.map(id => this.#productById().get(id)).filter((p): p is ProductRow => !!p);
    const options: ScheduleDemandTier[] = [''];
    if (chosen.some(p => this.hasTier(p, 'Peak'))) options.push('Peak');
    if (chosen.some(p => this.hasTier(p, 'Valley'))) options.push('Valley');
    return options;
  }

  // ── Validation hints ─────────────────────────────────────────────────────────

  durationInvalid(): boolean {
    return this.validationAttempted() && !((this.band().durationMin ?? 0) > 0);
  }

  dayInvalid(dowKey: string): boolean {
    return this.validationAttempted() && this.slotsFor(dowKey).length === 0;
  }

  slotStartInvalid(slot: SessionSlotV1): boolean {
    return this.validationAttempted() && !HM.test(String(slot.start ?? ''));
  }

  slotProductsInvalid(slot: SessionSlotV1): boolean {
    return this.validationAttempted() && slot.productIds.length === 0;
  }

  // ── Weekday + duration ───────────────────────────────────────────────────────

  toggleWeekday(dow: number): void {
    const only = this.band().onlyDows ?? [];
    const next = only.includes(dow) ? only.filter(d => d !== dow) : [...only, dow];
    this.#emit({ ...this.band(), onlyDows: next.sort((a, b) => a - b) });
  }

  setDuration(value: string): void {
    const n = Number(value);
    this.#emit({ ...this.band(), durationMin: Number.isFinite(n) && n > 0 ? Math.floor(n) : undefined });
  }

  toggleDayCollapsed(dowKey: string): void {
    this.collapsedDays.update(current => ({ ...current, [dowKey]: !this.isDayCollapsed(dowKey) }));
  }

  // ── Slot editing ─────────────────────────────────────────────────────────────

  addSlot(dowKey: string): void {
    this.#setDowSlots(dowKey, [...this.slotsFor(dowKey), this.#newSlot('', '', this.#allProductIds())]);
  }

  removeSlot(dowKey: string, slotId: string): void {
    this.#setDowSlots(
      dowKey,
      this.slotsFor(dowKey).filter(slot => slot.id !== slotId),
    );
  }

  setSlotStart(dowKey: string, slotId: string, value: string): void {
    this.#patchSlot(dowKey, slotId, slot => ({ ...slot, start: value.trim() }));
  }

  setSlotTier(dowKey: string, slotId: string, value: string): void {
    this.#patchSlot(dowKey, slotId, slot => ({ ...slot, tier: this.#normalizeTier(value) }));
  }

  toggleSlotProduct(dowKey: string, slotId: string, productId: string): void {
    this.#patchSlot(dowKey, slotId, slot => {
      const productIds = slot.productIds.includes(productId)
        ? slot.productIds.filter(id => id !== productId)
        : [...slot.productIds, productId];
      const tierStillValid = this.tierOptionsFor(productIds).includes(slot.tier);
      return { ...slot, productIds, tier: tierStillValid ? slot.tier : '' };
    });
  }

  // ── Per-day recurrence modal ───────────────────────────────────────────────────

  /** Whether the product is selected in the shared generator. */
  hasProduct(productId: string): boolean {
    return this.generator.productIds().includes(productId);
  }

  toggleProduct(productId: string): void {
    this.generator.productIds.update(ids => (ids.includes(productId) ? ids.filter(id => id !== productId) : [...ids, productId]));
  }

  /** Open the modal in single-weekday mode ("add multiple time slots" for one day). */
  openSingleDayGenerator(dowKey: string): void {
    this.recurrenceDow.set(dowKey);
    this.generatorMode.set('day');
    this.#resetGenerator(this.generator);
    this.generator.open.set(true);
  }

  /** Open the modal in multi-weekday mode ("generate multiple days"). */
  openWeekDaysGenerator(): void {
    this.generatorMode.set('days');
    this.#resetGenerator(this.generator);
    this.generateDows.set(Object.fromEntries(this.openWeekdays().map(wd => [wd.key, true])));
    this.generator.open.set(true);
  }

  closeGenerator(): void {
    this.generator.open.set(false);
  }

  isGenerateDow(dowKey: string): boolean {
    return this.generateDows()[dowKey] ?? false;
  }

  toggleGenerateDow(dowKey: string): void {
    this.generateDows.update(current => ({ ...current, [dowKey]: !this.isGenerateDow(dowKey) }));
  }

  applyGenerator(): void {
    if (this.generatorMode() === 'days') {
      const selected = this.openWeekdays().filter(wd => this.isGenerateDow(wd.key));
      if (!selected.length) {
        this.generator.error.set('informationRequests.schedule.weekdays.generateNoDays');
        return;
      }
      const generated = this.#generateSlots(this.generator);
      if (!generated) return;
      const dowSlots = { ...(this.band().dowSlots ?? {}) };
      for (const wd of selected) {
        dowSlots[wd.key] = [...(dowSlots[wd.key] ?? []), ...generated.map(slot => ({ ...slot, id: this.#uid() }))];
      }
      this.#emit({ ...this.band(), dowSlots });
    } else {
      const generated = this.#generateSlots(this.generator);
      if (!generated) return;
      const dowKey = this.recurrenceDow();
      this.#setDowSlots(dowKey, [...this.slotsFor(dowKey), ...generated]);
    }
    this.generator.open.set(false);
  }

  // ── Internals ──────────────────────────────────────────────────────────────

  #resetGenerator(gen: SlotGenerator): void {
    gen.from.set('');
    gen.to.set('');
    gen.each.set(null);
    gen.tier.set('');
    gen.productIds.set(this.#allProductIds());
    gen.error.set('');
  }

  /** Build the slots described by a generator; sets its error and returns null when the recurrence is invalid. */
  #generateSlots(gen: SlotGenerator): SessionSlotV1[] | null {
    const starts = this.#generateStarts(gen.from(), gen.to(), gen.each());
    if (!starts) {
      gen.error.set('informationRequests.schedule.weekdays.recurrenceInvalid');
      return null;
    }
    const tier = gen.tier();
    const productIds = [...gen.productIds()];
    return starts.map(start => this.#newSlot(start, tier, productIds));
  }

  #emit(band: NamedDateRangeV1): void {
    this.bandChange.emit(band);
  }

  #setDowSlots(dowKey: string, slots: SessionSlotV1[]): void {
    const dowSlots = { ...(this.band().dowSlots ?? {}) };
    if (slots.length) dowSlots[dowKey] = slots;
    else delete dowSlots[dowKey];
    this.#emit({ ...this.band(), dowSlots });
  }

  #patchSlot(dowKey: string, slotId: string, updater: (slot: SessionSlotV1) => SessionSlotV1): void {
    this.#setDowSlots(
      dowKey,
      this.slotsFor(dowKey).map(slot => (slot.id === slotId ? updater(slot) : slot)),
    );
  }

  #newSlot(start: string, tier: ScheduleDemandTier, productIds: string[]): SessionSlotV1 {
    return { id: this.#uid(), productIds: [...productIds], start, tier };
  }

  #allProductIds(): string[] {
    return this.products().map(p => p.id);
  }

  #normalizeTier(value: string): ScheduleDemandTier {
    return value === 'Peak' || value === 'Standard' || value === 'Valley' || value === 'Closed' ? value : '';
  }

  /** Build the HH:MM start times for a recurrence; null when the inputs are invalid. */
  #generateStarts(from: string, to: string, each: number | null): string[] | null {
    const first = this.#hmToMin(from);
    const last = this.#hmToMin(to);
    const step = Number(each);
    if (first === null || last === null || !Number.isFinite(step) || step <= 0 || last < first) return null;
    const out: string[] = [];
    for (let cur = first; cur <= last; cur += Math.floor(step)) out.push(this.#minToHm(cur));
    return out;
  }

  #hmToMin(value: string): number | null {
    const m = HM.exec(String(value ?? '').trim());
    if (!m) return null;
    const [h, mm] = value.split(':').map(Number);
    if (!Number.isFinite(h) || !Number.isFinite(mm) || h < 0 || h > 23 || mm < 0 || mm > 59) return null;
    return h * 60 + mm;
  }

  #minToHm(value: number): string {
    const day = 24 * 60;
    const normalized = ((Math.floor(value) % day) + day) % day;
    return `${String(Math.floor(normalized / 60)).padStart(2, '0')}:${String(normalized % 60).padStart(2, '0')}`;
  }

  #uid(): string {
    const c = globalThis.crypto as { randomUUID?: () => string } | undefined;
    return `slot-${c?.randomUUID ? c.randomUUID() : `${Date.now()}-${Math.floor(Math.random() * 1e6)}`}`;
  }
}
