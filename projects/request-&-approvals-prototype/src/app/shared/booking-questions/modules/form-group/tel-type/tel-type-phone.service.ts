  countryCodes(): Observable<Array<TelTypeCountryCode>> {
    const countriesCodes: Array<TelTypeCountryCode> = [];
    const countries: CountryCode[] = getCountries();
    countries.forEach((countryCode: CountryCode, index) => {
      const code = getCountryCallingCode(countryCode);
      countriesCodes.push({
        id: `${index}`,
        code: code,
        countryName: countryCode,
      });
    });
    return of(phonePrefixed);
  }
