import type { TemplateRef } from '@angular/core';

import type { Observable } from 'rxjs';

import type { IgntAlertSentiment } from '../../alert/models/alert.model';

/**
 * Colour intent supported by `IgntToastService`. Shares its domain with `IgntAlertSentiment`.
 */
export type IgntToastSentiment = IgntAlertSentiment;

interface IgntToastBaseConfig {
  /**
   * Label of the built-in action button (rendered as `contrast sentiment="neutral" size="small" variant="secondary"`).
   * Omit for a toast without an action.
   */
  actionLabel?: string;
  /**
   * Full control over the actions area: anything declared here (one or more buttons, a link, a
   * toggle) replaces the default `actionLabel` button entirely.
   */
  actions?: TemplateRef<unknown>;
  /**
   * Milliseconds before the toast auto-dismisses. Defaults to 4000 for `info`, `accent`, `positive` and `neutral` and
   * to 7000 for `warning` and `danger`. `Infinity`, `0` or a negative value keeps the toast until it is dismissed.
   * The timer pauses while the toast is hovered or contains focus (WCAG 2.2.1 Timing Adjustable).
   */
  duration?: number;
  /**
   * Colour intent of the toast. Default `info`.
   * - `info` — an informational message.
   * - `accent` — a contextual tip, not tied to a status.
   * - `positive` — success confirmation.
   * - `warning` — a caution the user should be aware of.
   * - `danger` — an error or destructive-state notice.
   * - `neutral` — the message is neutral in tone, or its semantics don't fit any of the other variants.
   */
  sentiment?: IgntToastSentiment;
  /**
   * Shows the dismiss (×) button. Default `true`.
   */
  showCloseButton?: boolean;
  /**
   * Bold heading shown above the body.
   */
  title?: string;
}

interface IgntToastDescriptionConfig {
  /**
   * Plain-text body.
   */
  description: string;
  content?: never;
}

interface IgntToastContentConfig {
  /**
   * Rich body declared in the caller's template (a list, a link, any markup). The caller's own styles apply to it and
   * the text colour inherits from the toast, so give links `color: inherit`.
   */
  content: TemplateRef<unknown>;
  description?: never;
}

/**
 * What `IgntToastService.show()` accepts. The body is either `description` text or a `content` template, never both.
 */
export type IgntToastConfig = IgntToastBaseConfig & (IgntToastContentConfig | IgntToastDescriptionConfig);

/**
 * Options accepted by the sentiment shorthands (`info()`, `positive()`, `warning()`, `danger()`), which take the
 * description as their first argument and fix the sentiment.
 */
export type IgntToastOptions = Omit<IgntToastBaseConfig, 'sentiment'>;

/**
 * Handle returned by `IgntToastService.show()`.
 */
export interface IgntToastRef {
  /**
   * Id of the toast, generated by `show()`.
   */
  id: string;
  /**
   * Removes the toast. A no-op once the toast is gone.
   */
  dismiss: () => void;
  /**
   * Emits once when the built-in action button is activated, then completes. Completes without emitting when the
   * toast goes away any other way, so a subscription never outlives its toast.
   */
  onAction: () => Observable<void>;
}

/**
 * A toast as rendered by the outlet: its config with every default and translation resolved, plus its id.
 * Exposed read-only through `IgntToastService.toasts`.
 */
export interface IgntToastState {
  /** Resolved from `IGNT_TOAST_TRANSLATIONS`; not settable per toast. */
  readonly closeButtonAriaLabel: string;
  /**
   * `''` when `content` is set.
   */
  readonly description: string;
  readonly duration: number;
  /**
   * Generated per `show()` call. Identifies the toast for `dismiss()` and for the outlet's `@for`.
   */
  readonly id: string;
  readonly sentiment: IgntToastSentiment;
  readonly showCloseButton: boolean;
  readonly actionLabel?: string;
  readonly actions?: TemplateRef<unknown>;
  readonly content?: TemplateRef<unknown>;
  readonly title?: string;
}
